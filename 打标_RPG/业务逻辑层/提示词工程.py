# -*- coding: utf-8 -*-
"""
提示词工程模块

负责构建 RPG Maker 精灵素材图像打标所需的系统提示词与用户分析提示词，
约束模型输出为严格合法的中文 JSON 对象（禁止解释性文字、禁止 markdown 代码块）。
"""

import sys
import os
import json

# 将项目根目录加入模块搜索路径，保证中文模块名可导入
项目根目录 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if 项目根目录 not in sys.path:
    sys.path.append(项目根目录)

# 统一 stdout 编码，避免中文打印乱码
sys.stdout.reconfigure(encoding="utf-8")

# 打标结果 JSON 字段说明：模型输出必须全部包含的字段与格式要求
打标字段说明 = {
    "名称": "短名（如 \"红衣骑士\"），不超过 10 字",
    "类型": "素材类型（如 \"角色精灵图\"、\"头像\"、\"地图图块\"、\"战斗图\"）",
    "内容描述": "一句话描述画面内容，不超过 60 字",
    "视觉特征": "数组，3-8 个字符串，描述外观与风格（如 \"像素风\"、\"红色披风\"、\"站立姿态\"）",
    "标签": "数组，3-10 个字符串，覆盖外观、身份、用途、风格等维度",
    "适用场景": "一句话说明该素材适合使用的游戏场景",
    "置信度": "0-1 之间的数字，表示你对分析结果的把握程度",
}

# 必填字段展示顺序（系统提示词与分析提示词共用）
打标字段顺序 = ["名称", "类型", "内容描述", "视觉特征", "标签", "适用场景", "置信度"]


def 构造字段说明文本():
    """生成【输出字段】说明文本（系统提示词与分析提示词共用）。"""
    行列表 = []
    for 字段 in 打标字段顺序:
        行列表.append("- {}：{}".format(字段, 打标字段说明[字段]))
    return "\n".join(行列表)


def 构造系统提示词():
    """
    构造系统提示词：定义"RPG Maker 游戏素材分析助手"角色与严格 JSON 输出要求。

    返回作为系统消息使用的提示词字符串。
    """
    return (
        "你是一位专业的 RPG Maker 游戏素材分析助手，精通 RPG Maker MV / MZ 的"
        "角色精灵图、头像、地图图块、战斗图等图像素材，擅长识别像素画风格、"
        "角色外观特征与游戏素材的实际用途。\n"
        "你将收到一张由 RPG Maker 素材自动切割得到的单格图片"
        "（通常为 48x48 或 64x64 像素的小图），请仔细观察图片内容"
        "并输出结构化的中文 JSON 打标结果。\n"
        "【输出字段（必须全部包含）】\n"
        + 构造字段说明文本()
        + "\n【输出要求】\n"
        + "- 只输出一个严格合法的 JSON 对象，字段与上述完全一致；\n"
        + "- 禁止输出任何解释性文字、前后缀说明或客套话；\n"
        + "- 禁止使用 markdown 代码块（不要写 ```json 和 ``` 围栏）；\n"
        + "- 名称、视觉特征、标签等文本一律使用中文。"
    )


def 构造分析提示词(素材信息):
    """
    根据素材信息构造用户分析提示词（用户消息文本）。

    入参 素材信息 为字典，通常包含：
    - 类型：素材类型（如 角色精灵图 / 头像 / 地图图块 / 战斗图）
    - 名称：素材名称（可选）
    - 来源文件：来源文件名（可选）
    - 坐标 / 切割坐标：切割坐标（行、列、像素区域，可为字典或字符串）
    - 序号 / 行 / 列：切割序号（可选）
    """
    素材信息 = 素材信息 if isinstance(素材信息, dict) else {}
    类型 = 素材信息.get("类型", "")
    名称 = 素材信息.get("名称", "")
    来源文件 = 素材信息.get("来源文件", "")
    坐标 = 素材信息.get("切割坐标", 素材信息.get("坐标", ""))
    if isinstance(坐标, (dict, list)):
        坐标 = json.dumps(坐标, ensure_ascii=False)
    序号 = 素材信息.get("序号", "")
    行 = 素材信息.get("行", "")
    列 = 素材信息.get("列", "")

    素材信息行 = ["【素材信息】"]
    if 类型:
        素材信息行.append("- 类型：{}".format(类型))
    if 名称:
        素材信息行.append("- 名称：{}".format(名称))
    if 来源文件:
        素材信息行.append("- 来源文件：{}".format(来源文件))
    if 坐标 not in (None, ""):
        素材信息行.append("- 切割坐标：{}".format(坐标))
    if 序号 not in (None, ""):
        素材信息行.append("- 序号：{}".format(序号))
    elif 行 not in (None, "") or 列 not in (None, ""):
        素材信息行.append("- 行列：第 {} 行 第 {} 列".format(行, 列))
    素材信息文本 = "\n".join(素材信息行)

    return (
        "请仔细观察并分析附带的 RPG Maker 游戏素材图片，"
        "输出符合要求的 JSON 打标结果。\n\n"
        + 素材信息文本
        + "\n\n【输出字段（必须全部包含）】\n"
        + 构造字段说明文本()
        + "\n\n【输出要求】\n"
        + "- 只输出一个严格合法的 JSON 对象，字段与上述完全一致；\n"
        + "- 不要输出 JSON 以外的任何文字（不要解释、不要总结、不要客套）；\n"
        + "- 不要使用 markdown 代码块（禁止 ``` 围栏）。"
    )


if __name__ == "__main__":
    # 直接运行本模块时打印提示词样例，便于人工检查
    print("=" * 60)
    print("系统提示词：")
    print("=" * 60)
    print(构造系统提示词())
    print()
    print("=" * 60)
    print("分析提示词（示例素材信息）：")
    print("=" * 60)
    示例素材信息 = {
        "类型": "角色精灵图",
        "名称": "红衣骑士",
        "来源文件": "Actor1.png",
        "切割坐标": {"行": 0, "列": 2, "x": 96, "y": 0, "宽": 48, "高": 48},
        "序号": 3,
    }
    print(构造分析提示词(示例素材信息))
