def 读取清单(文件名):
    """读取 进度\文件名 下的 JSON 清单，不存在时返回空列表。"""
    清单路径 = os.path.join(获取路径("进度目录"), 文件名)
    if os.path.exists(清单路径):
        try:
            with open(清单路径, "r", encoding="utf-8") as 文件对象:
                return json.load(文件对象)
        except (OSError, json.JSONDecodeError) as 异常:
            写日志("读取清单 {} 失败：{}".format(文件名, 异常), "警告")
    return []


def 写入清单(文件名, 数据列表):
    """将数据列表覆盖写回 进度\文件名 下的 JSON 清单，返回清单完整路径。"""
    清单路径 = os.path.join(获取路径("进度目录"), 文件名)
    with open(清单路径, "w", encoding="utf-8") as 文件对象:
        json.dump(数据列表, 文件对象, ensure_ascii=False, indent=2)
    return 清单路径


