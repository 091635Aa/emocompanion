def 组装记录(源路径, 文件名, 规格, 素材ID, 格文件路径, 行, 列, x0, y0, 宽, 高, 空块):
    """组装一条切割清单记录。"""
    return {
        "素材ID": 素材ID,
        "路径": 格文件路径,
        "来源文件": 文件名,
        "来源路径": 源路径,
        "类型": 规格["类型"],
        "类型标识": 规格["目录前缀"],
        "坐标": {"行": 行, "列": 列},
        "像素区域": {"x": x0, "y": y0, "宽": 宽, "高": 高},
        "空块": 空块,
        "缩略图路径": "",
    }


def 保存格与缩略图(区域, 格文件路径, 空块, 生成缩略图开关):
    """非空块时保存格子文件并生成缩略图，返回缩略图路径（失败或空块返回空串）。"""
    缩略图路径 = ""
    if 空块:
        return 缩略图路径
    os.makedirs(os.path.dirname(格文件路径), exist_ok=True)
    区域.save(格文件路径)
    if 生成缩略图开关:
        缩略图路径 = os.path.join(
            os.path.dirname(格文件路径), "缩略图",
            os.path.splitext(os.path.basename(格文件路径))[0] + ".png")
        if 生成缩略图(区域, 缩略图路径):
            return 缩略图路径
        return ""
    return 缩略图路径


def 切割普通网格(源路径, 源图, 规格, 输出根, 主名):
    """
    普通网格切割：头像 / 图块 A5 / B/C/D/E / 侧视图战斗图。

    按 行数 x 列数 逐格切割，产出文件命名为 <主名>_{行}x{列}.png。
    """
    配置 = 获取配置()
    生成缩略图开关 = bool(配置.get("流水线", {}).get("生成缩略图", True))
    行数 = 规格["行数"]
    列数 = 规格["列数"]
    单格宽 = 规格["单格宽"]
    单格高 = 规格["单格高"]
    实际宽, 实际高 = 源图.size
    # 防止规格与图片实际尺寸不一致导致越界
    实际行数 = min(行数, 实际高 // 单格高)
    实际列数 = min(列数, 实际宽 // 单格宽)
    if 实际行数 < 行数 or 实际列数 < 列数:
        写日志("警告：{} 实际尺寸 {}x{} 小于规格 {}x{}，按可切部分切割".format(
            主名, 实际宽, 实际高, 列数 * 单格宽, 行数 * 单格高), "警告")
    记录列表 = []
    for 行 in range(实际行数):
        for 列 in range(实际列数):
            x0 = 列 * 单格宽
            y0 = 行 * 单格高
            区域 = 源图.crop((x0, y0, x0 + 单格宽, y0 + 单格高))
            空块 = 是否空块(区域)
            格文件路径 = os.path.join(输出根, "{}_R{}C{}.png".format(主名, 行 + 1, 列 + 1))
            缩略图路径 = 保存格与缩略图(区域, 格文件路径, 空块, 生成缩略图开关)
            素材ID = "{}__{}__R{}C{}".format(主名, 规格["目录前缀"], 行 + 1, 列 + 1)
            记录 = 组装记录(源路径, os.path.basename(源路径), 规格, 素材ID,
                          格文件路径, 行 + 1, 列 + 1, x0, y0, 单格宽, 单格高, 空块)
            记录["缩略图路径"] = 缩略图路径
            记录列表.append(记录)
    return 记录列表


def 切割角色图(源路径, 源图, 规格, 输出根, 主名):
    """
    角色图切割：
    - 满版角色精灵图：先切 8 个角色子图（144x192），再记录每角色 12 帧坐标并切帧文件
    - 单角色精灵图（$ 前缀）：直接切 12 帧
    """
    配置 = 获取配置()
    生成缩略图开关 = bool(配置.get("流水线", {}).get("生成缩略图", True))
    角色行数 = 规格.get("角色行数", 4)
    角色列数 = 规格.get("角色列数", 3)
    单格宽 = 规格["单格宽"]
    单格高 = 规格["单格高"]
    角色子图宽 = 角色列数 * 单格宽   # 144
    角色子图高 = 角色行数 * 单格高   # 192
    记录列表 = []

    if 规格["类型"] == "满版角色精灵图":
        # 整图角色布局：规格 行数 x 列数 = 2 行 x 4 列 = 8 角色
        角色布局行数 = 规格["行数"]
        角色布局列数 = 规格["列数"]
        for 角色行 in range(角色布局行数):
            for 角色列 in range(角色布局列数):
                角色序号 = 角色行 * 角色布局列数 + 角色列 + 1
                x0 = 角色列 * 角色子图宽
                y0 = 角色行 * 角色子图高
                # 保存角色子图（144x192）
                角色图区域 = 源图.crop((x0, y0, x0 + 角色子图宽, y0 + 角色子图高))
                角色文件路径 = os.path.join(输出根, "{}_角色{}.png".format(主名, 角色序号))
                os.makedirs(输出根, exist_ok=True)
                角色图区域.save(角色文件路径)
                # 记录该角色的 12 帧坐标并切帧文件
                for 帧行 in range(角色行数):
                    for 帧列 in range(角色列数):
                        帧序号 = 帧行 * 角色列数 + 帧列 + 1
                        帧x0 = x0 + 帧列 * 单格宽
                        帧y0 = y0 + 帧行 * 单格高
                        帧区域 = 源图.crop((帧x0, 帧y0, 帧x0 + 单格宽, 帧y0 + 单格高))
                        空块 = 是否空块(帧区域)
                        帧目录 = os.path.join(输出根, "帧")
                        帧文件路径 = os.path.join(
                            帧目录, "{}_角色{}_帧{}.png".format(主名, 角色序号, 帧序号))
                        缩略图路径 = 保存格与缩略图(帧区域, 帧文件路径, 空块, 生成缩略图开关)
                        素材ID = "{}__角色{}__帧{}".format(主名, 角色序号, 帧序号)
                        记录 = 组装记录(源路径, os.path.basename(源路径), 规格, 素材ID,
                                      帧文件路径, 角色序号, 帧序号, 帧x0, 帧y0,
                                      单格宽, 单格高, 空块)
                        记录["坐标"] = {"角色序号": 角色序号, "帧序号": 帧序号,
                                       "行": 帧行 + 1, "列": 帧列 + 1}
                        记录["缩略图路径"] = 缩略图路径
                        记录列表.append(记录)
    else:
        # 单角色精灵图：3 列 x 4 行 12 帧
        for 帧行 in range(角色行数):
            for 帧列 in range(角色列数):
                帧序号 = 帧行 * 角色列数 + 帧列 + 1
                x0 = 帧列 * 单格宽
                y0 = 帧行 * 单格高
                帧区域 = 源图.crop((x0, y0, x0 + 单格宽, y0 + 单格高))
                空块 = 是否空块(帧区域)
                帧文件路径 = os.path.join(输出根, "{}_帧{}.png".format(主名, 帧序号))
                缩略图路径 = 保存格与缩略图(帧区域, 帧文件路径, 空块, 生成缩略图开关)
                素材ID = "{}__角色1__帧{}".format(主名, 帧序号)
                记录 = 组装记录(源路径, os.path.basename(源路径), 规格, 素材ID,
                              帧文件路径, 1, 帧序号, x0, y0, 单格宽, 单格高, 空块)
                记录["坐标"] = {"角色序号": 1, "帧序号": 帧序号,
                               "行": 帧行 + 1, "列": 帧列 + 1}
                记录["缩略图路径"] = 缩略图路径
                记录列表.append(记录)
    return 记录列表


def 切割自动图块(源路径, 源图, 规格, 输出根, 主名):
    """
    自动图块按"整块"切割：
    - autotile_animated（A1）：每 3 行一带，带内 2 个 6x3 动画块 + 2 个 2x3 静态块
    - autotile_2x3（A2）：整块 96x144（2x3），8 列 x 4 行
    - autotile_2x2（A3）：整块 96x96（2x2），8 列 x 4 行
    - autotile_mixed（A4）：2x3 / 2x2 自动块交替行（行高序列 3,2,3,2,3,2）
    """
    配置 = 获取配置()
    生成缩略图开关 = bool(配置.get("流水线", {}).get("生成缩略图", True))
    单格 = 规格["单格宽"]
    记录列表 = []
    特殊布局 = 规格["特殊布局"]

    def 切整块(x0, y0, 块宽, 块高, 行, 列):
        区域 = 源图.crop((x0, y0, x0 + 块宽, y0 + 块高))
        空块 = 是否空块(区域)
        格文件路径 = os.path.join(输出根, "{}_R{}C{}.png".format(主名, 行, 列))
        缩略图路径 = 保存格与缩略图(区域, 格文件路径, 空块, 生成缩略图开关)
        素材ID = "{}__{}__R{}C{}".format(主名, 规格["目录前缀"], 行, 列)
        记录 = 组装记录(源路径, os.path.basename(源路径), 规格, 素材ID,
                      格文件路径, 行, 列, x0, y0, 块宽, 块高, 空块)
        记录["缩略图路径"] = 缩略图路径
        记录列表.append(记录)

    if 特殊布局 == "autotile_animated":
        # A1：整图 768x576，块行带高 3 格（144px），共 4 带
        带数 = 规格["整图高"] // (3 * 单格)
        动画块宽 = 6 * 单格
        静态块宽 = 2 * 单格
        块高 = 3 * 单格
        for 带 in range(带数):
            y0 = 带 * 块高
            行 = 带 + 1
            for i in range(2):
                # 动画块 6x3
                切整块(i * 动画块宽, y0, 动画块宽, 块高, 行, i + 1)
            for i in range(2):
                # 静态块 2x3
                切整块(2 * 动画块宽 + i * 静态块宽, y0, 静态块宽, 块高, 行, 3 + i)
    elif 特殊布局 == "autotile_2x3":
        # A2：整图 768x576，整块 96x144，8 列 x 4 行
        块宽 = 2 * 单格
        块高 = 3 * 单格
        列数 = 规格["整图宽"] // 块宽
        行数 = 规格["整图高"] // 块高
        for 行 in range(行数):
            for 列 in range(列数):
                切整块(列 * 块宽, 行 * 块高, 块宽, 块高, 行 + 1, 列 + 1)
    elif 特殊布局 == "autotile_2x2":
        # A3：整图 768x384，整块 96x96，8 列 x 4 行
        块宽 = 2 * 单格
        块高 = 2 * 单格
        列数 = 规格["整图宽"] // 块宽
        行数 = 规格["整图高"] // 块高
        for 行 in range(行数):
            for 列 in range(列数):
                切整块(列 * 块宽, 行 * 块高, 块宽, 块高, 行 + 1, 列 + 1)
    elif 特殊布局 == "autotile_mixed":
        # A4：整图 768x720，2x3 / 2x2 自动块交替行（行高序列 3,2,3,2,3,2）
        块宽 = 2 * 单格
        行高序列 = [3, 2, 3, 2, 3, 2]
        当前y = 0
        for 行, 行高 in enumerate(行高序列):
            块高 = 行高 * 单格
            列数 = 规格["整图宽"] // 块宽
            for 列 in range(列数):
                切整块(列 * 块宽, 当前y, 块宽, 块高, 行 + 1, 列 + 1)
            当前y += 块高
    return 记录列表


def 切割单个素材(源路径, 规格, 判定说明):
    """按规格将单个源图切割为格子文件，返回切割记录列表。"""
    文件名 = os.path.basename(源路径)
    主名 = os.path.splitext(文件名)[0]
    输出根 = os.path.join(获取路径("分割素材目录"), 规格["目录前缀"], 主名)
    os.makedirs(输出根, exist_ok=True)

    with Image.open(源路径) as 图片对象:
        源图 = 图片对象.convert("RGBA")

    写日志("切割素材 {}：{}（{}）".format(文件名, 规格["类型"], 判定说明), "信息")

    特殊布局 = 规格.get("特殊布局")
    if 特殊布局 == "角色":
        return 切割角色图(源路径, 源图, 规格, 输出根, 主名)
    if 特殊布局 and str(特殊布局).startswith("autotile"):
        return 切割自动图块(源路径, 源图, 规格, 输出根, 主名)
    return 切割普通网格(源路径, 源图, 规格, 输出根, 主名)


# ============================================================
# 主流程
# ============================================================
def 分割全部():
    """
    递归扫描源素材目录下所有 PNG，按规格切割并写入切割清单。

    返回摘要字典：处理文件数 / 新增格子数 / 跳过数 / 未识别数 / 空块数 / 错误数。
    """
    源素材目录 = 获取路径("源素材目录")
    切割清单 = 读取清单(切割清单文件名)
    未识别清单 = 读取清单(未识别清单文件名)

    # 断点续切：源文件已在清单记录 且 对应产出文件已存在 -> 跳过
    已切割来源 = set()
    for 记录 in 切割清单:
        产出路径 = 记录.get("路径") or ""
        if 记录.get("来源路径") and os.path.exists(产出路径):
            已切割来源.add(记录["来源路径"])

    摘要 = {
        "源素材目录": 源素材目录,
        "处理文件数": 0,
        "新增格子数": 0,
        "跳过数": 0,
        "未识别数": 0,
        "空块数": 0,
        "错误数": 0,
    }
    本轮新增记录 = []
    本轮未识别 = []

    写日志("开始扫描源素材目录：{}".format(源素材目录), "信息")
    for 根目录, 子目录列表, 文件列表 in os.walk(源素材目录):
        for 文件名 in 文件列表:
            if not 文件名.lower().endswith(".png"):
                continue
            源路径 = os.path.normpath(os.path.join(根目录, 文件名))
            if 源路径 in 已切割来源:
                摘要["跳过数"] += 1
                continue
            # 识别规格：优先覆盖规格，其次自动识别
            覆盖规格 = 获取覆盖规格(源路径)
            if 覆盖规格:
                规格 = 覆盖规格
                判定说明 = "配置覆盖规格"
            else:
                识别结果 = 识别素材(源路径)
                if 识别结果 is None:
                    本轮未识别.append({
                        "文件路径": 源路径,
                        "文件名": 文件名,
                        "原因": "无法识别素材规格（尺寸不匹配且无覆盖配置）",
                    })
                    摘要["未识别数"] += 1
                    写日志("未识别素材已记录：{}".format(源路径), "警告")
                    continue
                规格 = 识别结果["规格"]
                判定说明 = 识别结果["判定说明"]
            摘要["处理文件数"] += 1
            try:
                新记录 = 切割单个素材(源路径, 规格, 判定说明)
                本轮新增记录.extend(新记录)
                摘要["新增格子数"] += len(新记录)
                摘要["空块数"] += sum(1 for 记录 in 新记录 if 记录["空块"])
            except Exception as 异常:
                摘要["错误数"] += 1
                写日志("切割失败 {}：{}".format(源路径, 异常), "错误")

    # 写回进度清单
    if 本轮新增记录:
        切割清单.extend(本轮新增记录)
        清单路径 = 写入清单(切割清单文件名, 切割清单)
        写日志("切割清单已更新：共 {} 条记录 -> {}".format(len(切割清单), 清单路径), "信息")
    if 本轮未识别:
        未识别清单.extend(本轮未识别)
        未识别路径 = 写入清单(未识别清单文件名, 未识别清单)
        写日志("未识别清单已更新：共 {} 条 -> {}".format(len(未识别清单), 未识别路径), "信息")

    写日志("分割完成：处理 {} 个文件，新增 {} 格，跳过 {}，未识别 {}，空块 {}，错误 {}".format(
        摘要["处理文件数"], 摘要["新增格子数"], 摘要["跳过数"],
        摘要["未识别数"], 摘要["空块数"], 摘要["错误数"]), "信息")
    return 摘要


def 获取分割清单():
    """读取切割清单并过滤空块，返回有效格子记录列表。"""
    切割清单 = 读取清单(切割清单文件名)
    return [记录 for 记录 in 切割清单 if not 记录.get("空块")]


