# 空块判定
# ============================================================
def 是否空块(图片区域):
    """
    判定格子是否为空块：Alpha 通道全为 0（或无可视像素）视为空块。

    优先使用 numpy 加速，numpy 不可用时回退为逐像素扫描。
    """
    try:
        import numpy as np
        数组 = np.array(图片区域)
        if 数组.ndim == 2:
            # 灰度图：全为 0 视为空块
            return not bool(数组.any())
        if 数组.shape[2] == 4:
            # RGBA：Alpha 全为 0 视为空块
            return not bool(数组[:, :, 3].any())
        if 数组.shape[2] == 3:
            # RGB：无可视像素（全黑）视为空块
            return not bool(数组.any())
    except Exception:
        pass
    # 兜底：逐像素扫描 Alpha
    try:
        if 图片区域.mode == "RGBA":
            阿尔法 = 图片区域.split()[-1]
            return 阿尔法.getextrema() == (0, 0)
        if 图片区域.mode in ("RGB", "L"):
            return 图片区域.getextrema() == (0, 0)
    except Exception:
        pass
    return False


def 生成缩略图(源图区域, 目标路径):
    """将格子区域缩放生成缩略图（最长边 96px）保存，返回 True/False。"""
    try:
        缩略图 = 源图区域.copy()
        缩略图.thumbnail((缩略图最大边长, 缩略图最大边长))
        os.makedirs(os.path.dirname(目标路径), exist_ok=True)
        缩略图.save(目标路径)
        return True
    except Exception as 异常:
        写日志("缩略图生成失败 {}：{}".format(目标路径, 异常), "警告")
        return False


