def 确保配置文件存在():
    """若 系统配置.json 不存在则写入默认配置，返回 True 表示本次新建。"""
    if os.path.exists(配置文件路径):
        return False
    配置目录 = os.path.dirname(配置文件路径)
    os.makedirs(配置目录, exist_ok=True)
    with open(配置文件路径, "w", encoding="utf-8") as 文件对象:
        json.dump(默认配置内容, 文件对象, ensure_ascii=False, indent=2)
    return True


def 创建全部目录():
    """遍历"路径"配置中的各目录键并自动创建，返回已确认的目录路径列表。"""
    配置 = 获取配置()
    路径配置 = 配置["路径"]
    创建的目录 = []
    工作目录 = 路径配置["工作目录"]
    os.makedirs(工作目录, exist_ok=True)
    for 键, 相对路径 in 路径配置.items():
        if 键 == "工作目录":
            continue
        完整路径 = 获取路径(键)
        创建的目录.append(完整路径)
    return 创建的目录


def 执行初始化():
    """
    执行初始化流程：确保配置文件存在、创建全部目录，返回初始化摘要字典。

    摘要字段：新建配置(是否新建)、目录数量、目录列表。
    """
    print("=" * 60)
    print("[初始化] 开始初始化系统……")
    print("=" * 60)
    新建配置 = 确保配置文件存在()
    if 新建配置:
        写日志("系统配置.json 不存在，已写入默认配置", "信息")
    目录列表 = 创建全部目录()
    摘要 = {
        "新建配置": 新建配置,
        "目录数量": len(目录列表),
        "目录列表": 目录列表,
    }
    写日志("初始化完成：共确认 {} 个目录".format(len(目录列表)), "信息")
    for 目录 in 目录列表:
        print("    - {}".format(目录))
    return 摘要


