def 获取规格列表():
    """返回内置素材规格注册表列表。"""
    return 素材规格注册表


def 净化文件名(文件名):
    """
    去除文件名开头的 $ / ! 前缀（含 !$ 组合）后返回。

    例如："$Hero.png" -> "Hero.png"；"!$Chest.png" -> "Chest.png"。
    """
    净化后 = 文件名
    while 净化后 and 净化后[0] in "!$":
        净化后 = 净化后[1:]
    return 净化后


def 获取覆盖规格(文件路径):
    """
    查询配置中的"素材规格覆盖"（键为文件名，值为 {单格宽, 单格高, 行数, 列数, 类型}）。

    返回构造好的规格 dict（目录前缀默认取目录名、整图宽高以实际图片为准由调用方补充）；
    未配置覆盖时返回 None。
    """
    配置 = 获取配置()
    覆盖表 = 配置.get("素材规格覆盖") or {}
    文件名 = os.path.basename(文件路径)
    主名 = os.path.splitext(文件名)[0]
    覆盖配置 = 覆盖表.get(文件名) or 覆盖表.get(主名)
    if not 覆盖配置:
        return None
    单格宽 = 覆盖配置.get("单格宽")
    单格高 = 覆盖配置.get("单格高")
    行数 = 覆盖配置.get("行数")
    列数 = 覆盖配置.get("列数")
    类型 = 覆盖配置.get("类型", "自定义网格")
    if not (单格宽 and 单格高 and 行数 and 列数):
        写日志("覆盖规格配置不完整（{}）：需要 单格宽/单格高/行数/列数".format(文件名), "警告")
        return None
    目录前缀 = 覆盖配置.get("目录前缀", "自定义")
    return {
        "类型": 类型,
        "目录前缀": 目录前缀,
        "整图宽": None,   # 整图尺寸以实际图片为准
        "整图高": None,
        "单格宽": int(单格宽),
        "单格高": int(单格高),
        "行数": int(行数),
        "列数": int(列数),
        "特殊布局": 覆盖配置.get("特殊布局"),
        "前缀语义": "配置手动覆盖",
        "来源覆盖": True,
    }


def 识别素材(文件路径):
    """
    结合图片实际尺寸与文件名前缀自动识别素材规格。

    返回 {"规格": dict, "判定说明": str}；
    无法识别时返回 None，并在日志中说明原因。
    """
    文件名 = os.path.basename(文件路径)
    净化名 = 净化文件名(文件名)
    主名 = os.path.splitext(净化名)[0]
    目录名 = os.path.basename(os.path.dirname(os.path.abspath(文件路径)))
    带美元前缀 = 文件名.startswith("$")

    # 1. 读取图片实际尺寸
    try:
        with Image.open(文件路径) as 图片对象:
            实际宽, 实际高 = 图片对象.size
    except Exception as 异常:
        写日志("图片打开失败 {}：{}".format(文件路径, 异常), "错误")
        return None

    # 2. 尺寸完全匹配的候选
    候选 = [规格 for 规格 in 素材规格注册表
            if 规格["整图宽"] == 实际宽 and 规格["整图高"] == 实际高]
    if not 候选:
        写日志("未识别素材 {}：尺寸 {}x{} 无匹配规格（可配置 素材规格覆盖）".format(
            文件路径, 实际宽, 实际高), "警告")
        return None

    判定依据 = ["尺寸 {}x{}".format(实际宽, 实际高)]

    # 3. 文件名前缀模式（A1-A5 / B-E 图块）优先筛选
    图块键 = None
    if len(主名) >= 2 and 主名[:2] in ("A1", "A2", "A3", "A4", "A5"):
        图块键 = 主名[:2]
    elif 主名 and 主名[:1] in ("B", "C", "D", "E"):
        图块键 = 主名[:1]
    if 图块键:
        图块候选 = [规格 for 规格 in 候选
                    if 规格["类型"].startswith("图块") and 图块键 in 规格["类型"]]
        if 图块候选:
            候选 = 图块候选
            判定依据.append("文件名前缀 {}".format(图块键))

    # 4. $ 前缀：优先单角色精灵图
    if 带美元前缀:
        单角色候选 = [规格 for 规格 in 候选 if 规格["类型"] == "单角色精灵图"]
        判定依据.append("$ 前缀")
        if 单角色候选:
            return {"规格": 单角色候选[0], "判定说明": "；".join(判定依据)}
        # 带 $ 前缀但不是单角色规格，则不返回任何角色类候选
        候选 = [规格 for 规格 in 候选 if 规格["类型"] != "满版角色精灵图"]

    # 5. 目录名辅助筛选（如 sv_actors / faces / characters / tilesets）
    目录候选 = [规格 for 规格 in 候选 if 规格["目录前缀"] == 目录名]
    if 目录候选:
        候选 = 目录候选
        判定依据.append("目录 {}".format(目录名))

    # 6. 多候选不确定时：输出警告并取首个（可配置覆盖修正）
    if len(候选) > 1:
        写日志("素材 {} 匹配到多个候选规格 {}，默认取首个「{}」，可配置 素材规格覆盖 修正".format(
            文件路径, [规格["类型"] for 规格 in 候选], 候选[0]["类型"]), "警告")
        判定依据.append("多候选取首个")
        return {"规格": 候选[0], "判定说明": "；".join(判定依据)}
    if len(候选) == 1:
        return {"规格": 候选[0], "判定说明": "；".join(判定依据)}

    写日志("未识别素材 {}：尺寸 {}x{} 匹配后无有效规格（可配置 素材规格覆盖）".format(
        文件路径, 实际宽, 实际高), "警告")
    return None


