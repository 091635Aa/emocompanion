def 创建推理引擎(架构类型: str, 模型路径: str, 参数: dict = None):
    """工厂函数：按架构类型创建推理引擎并加载模型。

    参数:
        架构类型: "V1简单回响" → V1推理引擎；"V通用架构" → 通用推理引擎。
        模型路径: 模型绝对路径（为空时仅创建实例，不加载）。
        参数: 推理参数字典（透传给引擎的 初始化）。

    返回:
        引擎实例（已执行 初始化）。
    """
    if 架构类型 == "V1简单回响":
        引擎 = V1推理引擎()
    elif 架构类型 == "V通用架构":
        引擎 = 通用推理引擎()
    else:
        raise ValueError(f"未知架构类型：{架构类型}，可用：V1简单回响 / V通用架构")
    if 模型路径:
        引擎.初始化(模型路径, 参数)
    return 引擎


