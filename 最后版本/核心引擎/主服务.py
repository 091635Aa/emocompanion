# -*- coding: utf-8 -*-
"""
主服务模块
==========
FastAPI 应用骨架：静态文件挂载、健康检查、配置接口、业务模块路由注册。

本模块只做骨架：
- 各业务模块（硬件检测/模型管理/数据预处理/打标引擎/日记生成/微调引擎/
  推理架构/达标评估）尚未实现时，注册路由会被 try/except 静默跳过，
  不影响服务启动；
- 业务模块后续按 核心引擎/接口约定.py 提供 `注册路由(app)` 即自动接入。
"""

import os
import threading
import webbrowser

from fastapi import FastAPI
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel

from 核心引擎 import 配置管理

# 创建 FastAPI 应用实例
应用 = FastAPI(
    title=配置管理.获取配置项("系统.项目名称", "一体化全流程AI应用"),
    version=配置管理.获取配置项("系统.版本", "0.1.0"),
    description="一体化全流程AI应用：数据预处理 → 打标 → 日记 → 微调 → 达标 → 推理",
)

# 静态文件挂载：/前端 → 前端/ 目录
前端目录 = 配置管理.解析路径("前端")
if os.path.isdir(前端目录):
    应用.mount("/前端", StaticFiles(directory=前端目录, html=True), name="前端")


# ---------- 健康检查接口 ----------
@应用.get("/api/健康")
def 健康检查() -> dict:
    """健康检查：返回服务状态、版本与项目名称。"""
    return {
        "状态": "正常",
        "版本": 配置管理.获取配置项("系统.版本", "0.1.0"),
        "项目名称": 配置管理.获取配置项("系统.项目名称", "一体化全流程AI应用"),
    }


# ---------- 配置接口 ----------
class 配置请求(BaseModel):
    """PUT /api/配置 的请求体：携带新的完整/部分配置字典。"""
    配置内容: dict


@应用.get("/api/配置")
def 获取配置() -> dict:
    """返回当前配置（路径字段已解析为绝对路径）。"""
    return 配置管理.读取配置()


@应用.put("/api/配置")
def 更新配置(请求: 配置请求) -> dict:
    """接收新配置并保存，返回保存结果与最新配置。"""
    成功 = 配置管理.保存配置(请求.配置内容)
    return {
        "状态": "已保存" if 成功 else "保存失败",
        "配置": 配置管理.读取配置(),
    }


# ---------- 模块注册机制 ----------
# 业务模块清单：动态导入并尝试调用其 `注册路由(app)`
业务模块清单 = [
    "核心引擎.硬件检测",
    "核心引擎.模型管理",
    "核心引擎.数据预处理",
    "核心引擎.打标引擎",
    "核心引擎.日记生成",
    "核心引擎.微调引擎",
    "核心引擎.推理架构",
    "核心引擎.达标评估",
]


def 注册模块路由(app) -> None:
    """动态导入各业务模块并注册其路由。

    每个模块若提供 `注册路由(app)` 函数则调用之；
    模块文件不存在、缺少依赖或注册失败时打印提示并跳过，不阻断启动。
    """
    for 模块名 in 业务模块清单:
        try:
            模块 = __import__(模块名, fromlist=["注册路由"])
        except Exception as 错误:
            print(f"[主服务] 跳过模块 {模块名}（尚未实现或缺少依赖）：{错误}")
            continue
        try:
            if hasattr(模块, "注册路由"):
                模块.注册路由(app)
                print(f"[主服务] 已注册模块路由：{模块名}")
        except Exception as 错误:
            print(f"[主服务] 模块 {模块名} 路由注册失败：{错误}")


# 应用创建时即注册各业务模块路由
注册模块路由(应用)


# ---------- 启动服务 ----------
def 启动服务(端口=None) -> None:
    """启动 uvicorn 服务。

    参数:
        端口: 覆盖配置中的默认端口；为 None 时使用配置项 "系统.默认端口"。
    """
    import uvicorn

    端口 = 端口 or 配置管理.获取配置项("系统.默认端口", 8765)
    页面地址 = f"http://127.0.0.1:{端口}/前端/页面入口.html"

    # 按配置决定是否自动打开浏览器（延迟打开，等服务就绪）
    if 配置管理.获取配置项("系统.自动打开浏览器", True):

        def _打开浏览器() -> None:
            webbrowser.open(页面地址)

        threading.Timer(1.5, _打开浏览器).start()

    print(f"[主服务] 页面入口：{页面地址}")
    uvicorn.run(应用, host="127.0.0.1", port=端口, log_level="info")


if __name__ == "__main__":
    启动服务()
