def 记录(步骤: str, 状态: str, 原因: str = "") -> None:
    """记录一步测试结果并打印控制台。"""
    步骤记录.append({"步骤": 步骤, "状态": 状态, "原因": 原因})
    行 = f"[{状态}] {步骤}"
    if 原因:
        行 += f"：{原因}"
    print(行)


def 检查依赖(模块包列表) -> list:
    """检查模块是否可导入，返回缺失列表 [(模块名, pip包名), ...]。"""
    缺失 = []
    for 模块名, 包名 in 模块包列表:
        try:
            __import__(模块名)
        except ImportError:
            缺失.append((模块名, 包名))
    return 缺失


def 读文本文件(路径: str) -> str:
    """按多种编码尝试读取文本文件。"""
    for 编码 in ("utf-8-sig", "utf-8", "gb18030"):
        try:
            with open(路径, "r", encoding=编码) as 文件:
                return 文件.read()
        except (UnicodeDecodeError, OSError):
            continue
    with open(路径, "r", encoding="utf-8", errors="replace") as 文件:
        return 文件.read()


# ==================================================================
# 步骤 1：准备文本输入（模拟无真实音视频）
# ==================================================================

def 步骤_文本输入() -> str:
    """创建 5 条不同话题的文本文件并上传清洗，返回清洗后文本。"""
    from 核心引擎 import 数据预处理

    临时路径 = os.path.join(脚本目录, "全流程_模拟输入.txt")
    with open(临时路径, "w", encoding="utf-8") as 文件:
        文件.write("\n".join(测试文本列表))
    结果 = 数据预处理.上传并清洗(临时路径, "文本")
    if not 结果.get("成功"):
        记录("1.文本输入→上传并清洗", "失败", str(结果.get("错误", "上传失败")))
        return ""
    上传路径 = 结果.get("文件路径") or 结果.get("路径") or 临时路径
    文本 = 读文本文件(上传路径).strip()
    if not 文本:
        记录("1.文本输入→上传并清洗", "失败", "清洗后文本为空")
        return ""
    记录("1.文本输入→上传并清洗", "通过",
         f"任务ID={结果.get('任务ID')}，模拟 5 条不同话题文本，文本长度={len(文本)}")
    return 文本


# ==================================================================
# 步骤 2：话题分割（断言 ≥ 2 段）
# ==================================================================

def 步骤_话题分割(文本: str) -> list:
    """话题分割并断言分段数 ≥ 2，返回片段列表（空表示失败）。

    文本输入无真实时间戳，故按 5 条文本各分配 8 秒构造模拟 ASR 时间戳
    （话题分割模块会把不足 最小片段秒 的片段合并，模拟时间戳可避免全段合并）。
    """
    from 核心引擎 import 数据预处理

    模拟时间戳 = []
    当前秒 = 0.0
    for 行 in 测试文本列表:
        模拟时间戳.append({"起始秒": round(当前秒, 2), "结束秒": round(当前秒 + 8.0, 2), "文本": 行})
        当前秒 += 8.0
    片段列表 = 数据预处理.话题分割(文本, 模拟时间戳)
    分段数 = len(片段列表)
    if 分段数 < 2:
        记录("2.话题分割", "失败",
             f"断言失败：分段数={分段数}（要求 ≥ 2），算法={片段列表[0].get('算法', '') if 片段列表 else '无'}")
        return []
    记录("2.话题分割", "通过",
         f"分段数={分段数}（≥ 2），算法={片段列表[0].get('算法', '')}，"
         f"摘要={[片段.get('话题摘要', '') for 片段 in 片段列表[:3]]}")
    return 片段列表


# ==================================================================
# 步骤 3：自动打标
# ==================================================================

def 步骤_打标(片段列表: list) -> bool:
    """自动打标并断言片段数 > 0。"""
    from 核心引擎 import 打标引擎

    打标后 = 打标引擎.自动打标(片段列表)
    if not 打标后:
        记录("3.自动打标", "失败", "打标结果为空")
        return False
    维度统计 = {}
    for 片段 in 打标后:
        维度 = 片段.get("情感维度", "")
        维度统计[维度] = 维度统计.get(维度, 0) + 1
    记录("3.自动打标", "通过", f"片段数={len(打标后)}，情感分布={维度统计}")
    return True


# ==================================================================
# 步骤 4：导出微调数据包
# ==================================================================

def 步骤_导出(片段列表: list) -> bool:
    """导出微调数据包并断言成功。"""
    from 核心引擎 import 打标引擎

    打标后 = 打标引擎.自动打标(片段列表)
    导出 = 打标引擎.导出数据包(打标后, "jsonl", "情感")
    if not 导出.get("成功"):
        记录("4.导出数据包", "失败", str(导出.get("错误", "导出失败")))
        return False
    if not os.path.exists(导出.get("路径", "")):
        记录("4.导出数据包", "失败", f"数据包文件不存在：{导出.get('路径')}")
        return False
    记录("4.导出数据包", "通过", f"条数={导出.get('条数')}，路径={导出.get('路径')}")
    return True


# ==================================================================
# 步骤 5：日记生成（教师模型未配置 → 降级模板）
# ==================================================================

def 步骤_日记() -> None:
    """生成角色日记；教师模型未配置时应全部走降级模板路径。"""
    from 核心引擎 import 日记生成

    人设 = {
        "姓名": "全流程测试角色", "性别": "女", "出生年份": 2008,
        "人设描述": "测试用的普通女孩",
    }
    参数 = {"起始年龄": 7, "当前年龄": 9, "每篇字数最小": 50, "每篇字数最大": 300}
    日记列表 = 日记生成.生成日记(人设, 数据目录="", 参数=参数)
    if not 日记列表:
        记录("5.日记生成", "失败", "日记列表为空")
        return
    来源统计 = {}
    for 篇 in 日记列表:
        来源 = 篇.get("来源") or "未知"
        来源统计[来源] = 来源统计.get(来源, 0) + 1
    降级比例 = 来源统计.get("降级模板", 0)
    if 降级比例 == len(日记列表):
        记录("5.日记生成", "通过",
             f"篇数={len(日记列表)}，全部来源=降级模板（教师模型未配置，降级路径验证通过），分布={来源统计}")
    else:
        记录("5.日记生成", "失败", f"存在非降级模板来源：{来源统计}（预期全部为降级模板）")


