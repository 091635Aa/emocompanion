def 步骤_微调() -> None:
    """微调：transformers/peft/datasets 缺失时跳过（依赖未安装）。"""
    缺失 = 检查依赖([("transformers", "transformers"), ("peft", "peft"), ("datasets", "datasets")])
    if 缺失:
        待安装命令.add(训练安装命令)
        缺失名 = "、".join(f"{模块}（{包}）" for 模块, 包 in 缺失)
        记录("6.微调", "跳过", f"依赖未安装：{缺失名}")
        return
    from 核心引擎 import 微调引擎

    结果 = 微调引擎.微调({"模型路径": "本地测试模型", "启用情感微调": True})
    if 结果.get("成功"):
        记录("6.微调", "通过", f"输出目录={结果.get('输出目录')}")
    else:
        记录("6.微调", "失败", str(结果.get("错误", "微调失败")))


def 步骤_达标() -> None:
    """达标评估：transformers 缺失时跳过（依赖未安装）。"""
    缺失 = 检查依赖([("transformers", "transformers")])
    if 缺失:
        待安装命令.add(评估安装命令)
        记录("7.达标评估", "跳过", "依赖未安装：transformers")
        return
    from 核心引擎 import 达标评估

    结果 = 达标评估.评估达标("本地测试模型")
    if 结果.get("成功"):
        记录("7.达标评估", "通过", f"综合得分={结果.get('综合得分')}")
    else:
        记录("7.达标评估", "失败", str(结果.get("错误", "评估失败")))


def 步骤_推理() -> None:
    """推理演示：transformers 缺失时跳过（依赖未安装）。"""
    缺失 = 检查依赖([("transformers", "transformers")])
    if 缺失:
        待安装命令.add(推理安装命令)
        记录("8.推理演示", "跳过", "依赖未安装：transformers")
        return
    from 核心引擎.推理架构 import V1推理引擎

    引擎 = V1推理引擎()
    try:
        初始化结果 = 引擎.初始化("本地测试模型")
        if not isinstance(初始化结果, dict) or not 初始化结果.get("成功"):
            错误 = 初始化结果.get("错误") if isinstance(初始化结果, dict) else str(初始化结果)
            记录("8.推理演示", "失败", f"初始化失败：{错误}")
            return
        生成结果 = 引擎.生成("你好")
        回复 = 生成结果.get("回复") if isinstance(生成结果, dict) else str(生成结果 or "")
        记录("8.推理演示", "通过" if 回复 else "失败",
             f"回复长度={len(回复)}" if 回复 else "生成了空回复")
    except Exception as 错误:
        记录("8.推理演示", "失败", f"推理异常：{错误}")
    finally:
        try:
            引擎.释放()
        except Exception:
            pass


# ==================================================================
# 步骤 9：编排器联动（用 全流程() 串联）
# ==================================================================

def 步骤_编排器联动(文本: str) -> None:
    """调用 全流程() 串联全部步骤，断言返回结构合法。"""
    from 核心引擎.全流程编排 import 全流程

    步骤配置 = {
        "数据输入": {"类型": "文本", "路径": os.path.join(脚本目录, "全流程_模拟输入.txt")},
        "预处理": True,
        "打标": True,
        "日记": {"人设": {"姓名": "编排测试角色", "出生年份": 2008},
                 "参数": {"起始年龄": 7, "当前年龄": 8, "每篇字数最小": 50, "每篇字数最大": 300}},
        "微调": {"模型路径": "本地测试模型", "启用情感微调": True},
        "达标": {"模型路径": "本地测试模型"},
        "推理": {"架构": "V1简单回响", "模型路径": "本地测试模型"},
    }
    进度记录 = []

    def 回调(百分比: float, 消息: str) -> None:
        进度记录.append((百分比, 消息))

    结果 = 全流程(步骤配置, 进度回调=回调)
    步骤结果 = 结果.get("步骤结果") if isinstance(结果, dict) else None
    汇总 = 结果.get("汇总") if isinstance(结果, dict) else None
    if not isinstance(步骤结果, dict) or not isinstance(汇总, dict):
        记录("9.编排器联动", "失败", "返回结构非法（缺少 步骤结果 / 汇总）")
        return
    缺失步骤 = [步骤 for 步骤 in ("数据输入", "预处理", "打标", "日记", "微调", "达标", "推理")
                 if 步骤 not in 步骤结果]
    if 缺失步骤:
        记录("9.编排器联动", "失败", f"步骤结果缺少：{'、'.join(缺失步骤)}")
        return
    有进度回调 = len(进度记录) > 0
    记录("9.编排器联动", "通过",
         f"步骤结果={len(步骤结果)} 步，汇总={汇总}，进度回调次数={len(进度记录)}"
         + ("" if 有进度回调 else "（无进度回调）"))


# ==================================================================
# 主流程
# ==================================================================

def 写报告() -> None:
    """把测试结果写入 测试\全流程测试报告.txt。"""
    通过数 = sum(1 for 条 in 步骤记录 if 条["状态"] == "通过")
    跳过数 = sum(1 for 条 in 步骤记录 if 条["状态"] == "跳过")
    失败数 = sum(1 for 条 in 步骤记录 if 条["状态"] == "失败")
    有失败 = 失败数 > 0

    行 = []
    行.append("=" * 60)
    行.append("一体化全流程AI应用 · 全流程测试报告")
    行.append(f"时间：{time.strftime('%Y-%m-%d %H:%M:%S')}")
    行.append("目标：文本模拟 视频/音频/文本 → 话题分割 → 打标 → 日记 → 微调 → 达标 → 推理")
    行.append("=" * 60)
    行.append("")
    行.append(f"待安装命令（依赖缺失，安装后可重新运行）：")
    if 待安装命令:
        for 命令 in sorted(待安装命令):
            行.append(f"  - {命令}")
    else:
        行.append("  （无）")
    行.append("")
    行.append("-" * 60)
    for 条 in 步骤记录:
        行.append(f"[{条['状态']}] {条['步骤']}" + (f"：{条['原因']}" if 条["原因"] else ""))
    行.append("")
    行.append("-" * 60)
    行.append(f"汇总：通过 {通过数} / 跳过 {跳过数} / 失败 {失败数}")
    行.append(f"总体：{'通过（全部通过或跳过）' if not 有失败 else '未通过（存在失败步骤）'}")
    行.append("")
    行.append(f"退出码：{1 if 有失败 else 0}")

    内容 = "\n".join(行)
    with open(报告路径, "w", encoding="utf-8") as 文件:
        文件.write(内容 + "\n")
    print("")
    print(内容)
    print(f"[全流程测试] 报告已写入：{报告路径}")


def 主入口() -> int:
    """主流程：逐步骤执行并输出 通过/跳过/失败，返回退出码。"""
    print("=" * 60)
    print("一体化全流程AI应用 · 全流程测试")
    print("=" * 60)

    文本 = 步骤_文本输入()
    片段列表 = []
    if 文本:
        片段列表 = 步骤_话题分割(文本)
    if 片段列表:
        步骤_打标(片段列表)
        步骤_导出(片段列表)
    else:
        # 前置失败时后续数据链路步骤记录为失败
        if not 文本:
            记录("2.话题分割", "失败", "依赖前置失败：文本输入失败")
            记录("3.自动打标", "失败", "依赖前置失败：话题分割失败")
            记录("4.导出数据包", "失败", "依赖前置失败：话题分割失败")
        else:
            记录("3.自动打标", "失败", "依赖前置失败：话题分割未达 2 段")
            记录("4.导出数据包", "失败", "依赖前置失败：话题分割未达 2 段")
    步骤_日记()
    步骤_微调()
    步骤_达标()
    步骤_推理()
    if 文本:
        步骤_编排器联动(文本)

    写报告()
    通过数 = sum(1 for 条 in 步骤记录 if 条["状态"] == "通过")
    跳过数 = sum(1 for 条 in 步骤记录 if 条["状态"] == "跳过")
    失败数 = sum(1 for 条 in 步骤记录 if 条["状态"] == "失败")
    print(f"[全流程测试] 汇总：通过 {通过数} / 跳过 {跳过数} / 失败 {失败数}")
    return 1 if 失败数 > 0 else 0


if __name__ == "__main__":
    sys.exit(主入口())
