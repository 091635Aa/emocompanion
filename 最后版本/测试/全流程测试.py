"""
全流程测试脚本（Task 12.3）
==========================
完整链路：视频/音频/文本 → 话题分割 → 打标 → 日记 → 微调 → 达标 → 推理。

无真实音视频时用文本输入模拟：
  1. 写 5 条不同话题的文本 → 上传并清洗
  2. 话题分割（断言分段数 ≥ 2）
  3. 自动打标（断言片段数 > 0）
  4. 导出微调数据包（断言成功）
  5. 日记生成（教师模型未配置 → 断言全部降级为内置模板）
  6. 微调（transformers/peft/datasets 缺失 → 跳过（依赖未安装））
  7. 达标（transformers 缺失 → 跳过（依赖未安装））
  8. 推理（transformers 缺失 → 跳过（依赖未安装））
  9. 编排器联动（用 全流程() 串联，断言返回结构合法）

输出：测试\全流程测试报告.txt（含每步 通过/跳过/失败 + 原因，开头汇总待安装命令）。
退出码：0（全部通过或跳过）、1（有失败）。
"""

