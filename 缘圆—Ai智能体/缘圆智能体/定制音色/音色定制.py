# -*- coding: utf-8 -*-
"""音色定制完整流程编排：数据集处理 → 最优片段筛选 → 音色注册 → 质量校验。

供后端集成调用（路由挂载由后续集成处理），默认声音库目录：
  数据目录()/定制音色/声音库   （即 项目根/定制音色/声音库，不存在则自动创建）
"""
from pathlib import Path

from 环境配置 import 数据目录
from 定制音色 import 数据集处理, 质量校验, 最优片段筛选, 音色注册

默认前缀 = "yuanyuan"


def 默认声音库目录():
    """数据目录()/定制音色/声音库，不存在则自动创建。"""
    目录 = 数据目录() / "定制音色" / "声音库"
    目录.mkdir(parents=True, exist_ok=True)
    return 目录


def 执行完整流程(数据集输入, 声音库目录=None, 前缀=默认前缀):
    """依次执行 处理 → 筛选 → 注册 → 校验，返回逐步结果 dict。

    参数：
      数据集输入   —— 单个音频文件路径，或含多个音频的目录路径
      声音库目录   —— 输出目录，默认 数据目录()/定制音色/声音库
      前缀         —— 音色名称前缀（默认 yuanyuan）

    返回：
      {
        "步骤": {
          "处理":   {"ok": bool, "结果": {...}, "错误": "..."},
          "筛选":   {"ok": bool, "结果": {...}, "错误": "..."},
          "注册":   {"ok": bool, "结果": {...}, "错误": "..."},
          "校验":   {"ok": bool, "结果": {...}, "错误": "..."},
        },
        "音色ID": "...",
        "最优片段路径": "...",
        "试听路径": "...",        # 最优片段.mp3（无 ffmpeg 时为 最优片段.wav）
        "选择报告路径": "...",
      }
    任一步失败立即返回，结果中带该步错误与上一步结果。
    """
    声音库目录 = Path(声音库目录) if 声音库目录 else 默认声音库目录()
    声音库目录.mkdir(parents=True, exist_ok=True)
    步骤结果 = {}

    # 步骤 1：数据集处理
    try:
        处理结果 = 数据集处理.处理(数据集输入, 声音库目录)
        步骤结果["处理"] = {"ok": True, "结果": 处理结果, "错误": ""}
    except Exception as 异常:
        步骤结果["处理"] = {"ok": False, "结果": None, "错误": str(异常)}
        return {"步骤": 步骤结果, "音色ID": None, "最优片段路径": None,
                "试听路径": None, "选择报告路径": None}

    # 步骤 2：最优片段筛选
    try:
        筛选报告 = 最优片段筛选.筛选(处理结果["全长路径"], 声音库目录)
        步骤结果["筛选"] = {"ok": True, "结果": 筛选报告, "错误": ""}
    except Exception as 异常:
        步骤结果["筛选"] = {"ok": False, "结果": None, "错误": str(异常)}
        return {"步骤": 步骤结果, "音色ID": None, "最优片段路径": None,
                "试听路径": None, "选择报告路径": None}

    最优片段路径 = 声音库目录 / "最优片段.wav"
    试听路径 = 声音库目录 / "最优片段.mp3"
    if not 试听路径.is_file():
        试听路径 = 最优片段路径

    # 步骤 3：音色注册
    try:
        注册结果 = 音色注册.注册(最优片段路径, 声音库目录, 前缀=前缀)
        步骤结果["注册"] = {"ok": bool(注册结果.get("成功")), "结果": 注册结果, "错误": ""}
        if not 注册结果.get("成功"):
            步骤结果["注册"]["错误"] = 注册结果.get("错误", "注册失败")
            return {"步骤": 步骤结果, "音色ID": None, "最优片段路径": str(最优片段路径),
                    "试听路径": str(试听路径), "选择报告路径": str(声音库目录 / "选择报告.json")}
    except Exception as 异常:
        步骤结果["注册"] = {"ok": False, "结果": None, "错误": str(异常)}
        return {"步骤": 步骤结果, "音色ID": None, "最优片段路径": str(最优片段路径),
                "试听路径": str(试听路径), "选择报告路径": str(声音库目录 / "选择报告.json")}

    音色ID = 注册结果.get("音色ID", "")

    # 步骤 4：质量校验
    try:
        校验结果 = 质量校验.校验(声音库目录, 音色ID)
        步骤结果["校验"] = {"ok": bool(校验结果.get("通过")), "结果": 校验结果, "错误": ""}
        if not 校验结果.get("通过"):
            步骤结果["校验"]["错误"] = 校验结果.get("错误", "校验失败")
    except Exception as 异常:
        步骤结果["校验"] = {"ok": False, "结果": None, "错误": str(异常)}

    return {"步骤": 步骤结果, "音色ID": 音色ID, "最优片段路径": str(最优片段路径),
            "试听路径": str(试听路径), "选择报告路径": str(声音库目录 / "选择报告.json")}
