# -*- coding: utf-8 -*-
"""最优片段筛选：从 24kHz 单声道全长音频中，用算法挑选
"信息密度最高、最清晰、最符合阿里云声音复刻要求"的 10~20 秒片段。

评分维度（均归一化后加权，迁移自旧工程 select_best_segment.py）：
  1) 语音占比       —— 连续清晰人声覆盖率（硬约束 ≥ 0.55）
  2) 最大连续停顿   —— 硬约束 ≤ 2.0 秒
  3) 信噪比(SNR)    —— 语音帧能量 / 底噪能量
  4) 信息密度       —— 音节数/秒（语速代理，即"承载信息量"）
  5) 能量调制系数   —— 语音起伏程度，音乐/平稳噪声低

评分 = 0.35×信息密度(音节率/5 封顶 1) + 0.25×SNR(/40 封顶 1)
      + 0.20×语音占比 + 0.20×能量调制系数(/1.5 封顶 1)

VAD：自适应能量阈值（噪声底 = RMS 15 分位，阈值 = max(噪声底×4, 0.002)），
     中值滤波 + 闭运算 + 开运算。

输出（声音库目录下）：
  - 最优片段.wav    (24kHz 16bit 单声道, 10~20s)
  - 最优片段.mp3    (试听用 192k，需 ffmpeg，缺失则跳过)
  - 选择报告.json
"""
import json
import os
import shutil
import subprocess
from pathlib import Path

import numpy as np
import soundfile as sf
from scipy import ndimage
from scipy.signal import find_peaks

采样率 = 24000
帧长 = int(0.025 * 采样率)   # 25ms
帧移 = int(0.010 * 采样率)   # 10ms
语音占比下限 = 0.55           # 硬约束：候选窗口语音占比下限
最大停顿上限秒 = 2.0          # 硬约束：候选窗口最大连续停顿上限
最短时长秒 = 10.0             # 最终裁剪最短时长
最长时长秒 = 20.0             # 最终裁剪最长时长
首尾留白秒 = 0.3              # 裁剪时首尾各保留的留白
音节峰最小间距秒 = 0.12        # 音节检测峰最小间距

# 评分权重
信息密度权重 = 0.35
信噪比权重 = 0.25
语音占比权重 = 0.20
调制权重 = 0.20
信息密度归一 = 5.0            # 音节率/5 封顶 1
信噪比归一 = 40.0             # SNR/40 封顶 1
调制归一 = 1.5                # 调制系数/1.5 封顶 1


def _帧能量(数据):
    """按 25ms 帧长 / 10ms 帧移计算帧 RMS。"""
    总数 = len(数据)
    帧数 = (总数 - 帧长) // 帧移 + 1
    输出 = np.empty(帧数, dtype=np.float32)
    for 索引 in range(帧数):
        起点 = 索引 * 帧移
        片段 = 数据[起点:起点 + 帧长]
        输出[索引] = np.sqrt(np.mean(片段 * 片段) + 1e-12)
    return 输出


def _最大连续停顿(掩码):
    """统计掩码中连续非语音帧的最大帧数。"""
    最大 = 0
    当前 = 0
    for 是否语音 in 掩码:
        if 是否语音:
            当前 = 0
        else:
            当前 += 1
            if 当前 > 最大:
                最大 = 当前
    return 最大


def _语音检测(能量):
    """自适应能量阈值 VAD：噪声底 = RMS 15 分位，阈值 = max(噪声底×4, 0.002)，
    再做中值滤波(size=3)、闭运算(7)、开运算(3)。返回 (语音掩码, 噪声底, 阈值)。"""
    噪声底 = float(np.percentile(能量, 15))
    阈值 = max(噪声底 * 4.0, 0.002)
    语音 = 能量 > 阈值
    语音 = ndimage.median_filter(语音.astype(np.uint8), size=3).astype(bool)
    语音 = ndimage.binary_closing(语音, structure=np.ones(7))
    语音 = ndimage.binary_opening(语音, structure=np.ones(3))
    return 语音, 噪声底, 阈值


def _音节检测(能量, 阈值):
    """对 RMS 包络（高斯平滑 σ=3）找峰，作为音节数代理。"""
    包络 = ndimage.gaussian_filter1d(能量, 3)
    峰, _ = find_peaks(包络, height=阈值,
                       distance=int(音节峰最小间距秒 / (帧移 / 采样率)))
    return 峰, 包络


def 筛选(全长路径, 声音库目录, 窗口秒=15.0, 步长秒=0.5):
    """从全长音频中筛选最优 10~20 秒片段。

    参数：
      全长路径     —— 数据集处理.处理() 生成的 24kHz 单声道全长音频
      声音库目录   —— 输出目录（最优片段.wav / 选择报告.json / 最优片段.mp3）
      窗口秒       —— 候选窗口长度（默认 15 秒）
      步长秒       —— 滑窗步长（默认 0.5 秒）

    返回：选择报告 dict（键名与旧版一致，另附中文键）。
    若无任何窗口通过硬约束则抛出 RuntimeError。
    """
    全长路径 = Path(全长路径)
    声音库目录 = Path(声音库目录)
    声音库目录.mkdir(parents=True, exist_ok=True)

    数据, 实际采样率 = sf.read(全长路径, dtype="float32")
    if 实际采样率 != 采样率:
        raise RuntimeError(f"全长音频采样率为 {实际采样率}Hz，期望 24000Hz。"
                           "请先用 数据集处理.处理() 统一重采样。")
    if 数据.ndim > 1:
        数据 = 数据.mean(axis=1)

    能量 = _帧能量(数据)
    帧数 = len(能量)
    时间轴 = np.arange(帧数) * 帧移 / 采样率

    # ---- VAD ----
    语音掩码, 噪声底, 阈值 = _语音检测(能量)

    # ---- 全局语音帧特征 ----
    语音帧能量 = 能量[语音掩码]
    全局平均信噪比 = float(np.mean(
        10.0 * np.log10((语音帧能量 ** 2) / (噪声底 ** 2) + 1e-9)))
    全局调制系数 = float(语音帧能量.std() / (语音帧能量.mean() + 1e-9))
    _, 包络 = _音节检测(能量, 阈值)

    # ---- 滑窗评分 ----
    窗口帧数 = int(窗口秒 / (帧移 / 采样率))
    步长帧数 = int(步长秒 / (帧移 / 采样率))
    最优 = None
    for 起点 in range(0, 帧数 - 窗口帧数 + 1, 步长帧数):
        掩码 = 语音掩码[起点:起点 + 窗口帧数]
        语音占比 = float(掩码.mean())
        最大停顿秒 = _最大连续停顿(掩码) * 帧移 / 采样率
        # 硬约束
        if 语音占比 < 语音占比下限 or 最大停顿秒 > 最大停顿上限秒:
            continue
        窗口能量 = 能量[起点:起点 + 窗口帧数]
        窗口包络 = 包络[起点:起点 + 窗口帧数]
        窗口峰, _ = find_peaks(窗口包络, height=阈值,
                               distance=int(音节峰最小间距秒 / (帧移 / 采样率)))
        信息密度 = len(窗口峰) / 窗口秒
        语音帧 = 窗口能量[掩码]
        信噪比 = 10.0 * np.log10(np.mean(语音帧 ** 2) / (噪声底 ** 2) + 1e-9)
        调制系数 = float(语音帧.std() / (语音帧.mean() + 1e-9))
        评分 = (信息密度权重 * min(信息密度 / 信息密度归一, 1.0)
                + 信噪比权重 * min(信噪比 / 信噪比归一, 1.0)
                + 语音占比权重 * 语音占比
                + 调制权重 * min(调制系数 / 调制归一, 1.0))
        if 最优 is None or 评分 > 最优["评分"]:
            最优 = {
                "起点帧": 起点, "终点帧": 起点 + 窗口帧数,
                "评分": float(评分), "语音占比": 语音占比,
                "最大停顿秒": 最大停顿秒, "信噪比": float(信噪比),
                "信息密度": float(信息密度), "调制系数": 调制系数,
                "起点秒": float(时间轴[起点]), "终点秒": float(时间轴[起点 + 窗口帧数 - 1]),
            }

    if 最优 is None:
        raise RuntimeError(
            "没有窗口通过硬约束（语音占比 ≥ 0.55、最大连续停顿 ≤ 2.0s）。"
            "请检查音频是否包含足够清晰、连续的人声。")

    # ---- 裁剪到语音范围并限制 10~20 秒 ----
    起点, 终点 = 最优["起点帧"], 最优["终点帧"]
    语音索引 = np.where(语音掩码[起点:终点])[0]
    起始 = 起点 + 语音索引[0] - int(首尾留白秒 / (帧移 / 采样率))
    结束 = 起点 + 语音索引[-1] + int(首尾留白秒 / (帧移 / 采样率))
    起始 = max(起始, 0)
    结束 = min(结束, 帧数 - 1)
    时长 = (结束 - 起始) * 帧移 / 采样率
    if 时长 > 最长时长秒:
        结束 = 起始 + int(最长时长秒 / (帧移 / 采样率))
    if 时长 < 最短时长秒:
        # 前后各扩展一半；不够则只向后/向前扩展（受全长边界约束）
        扩展帧 = int((最短时长秒 - 时长) / (帧移 / 采样率)) // 2
        起始 = max(0, 起始 - 扩展帧)
        结束 = min(帧数 - 1, 结束 + 扩展帧)
        剩余帧 = int(最短时长秒 / (帧移 / 采样率)) - (结束 - 起始)
        if 剩余帧 > 0:
            起始 = max(0, 起始 - 剩余帧)
            结束 = min(帧数 - 1, 结束 + 剩余帧)
    起始秒 = 起始 * 帧移 / 采样率
    结束秒 = 结束 * 帧移 / 采样率
    片段 = 数据[int(起始秒 * 采样率): int(结束秒 * 采样率)]

    # ---- 导出 ----
    波形路径 = 声音库目录 / "最优片段.wav"
    mp3路径 = 声音库目录 / "最优片段.mp3"
    sf.write(波形路径, 片段, 采样率, subtype="PCM_16")
    mp3是否生成 = False
    if shutil.which("ffmpeg"):
        try:
            subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", str(波形路径),
                            "-b:a", "192k", str(mp3路径)], check=True)
            mp3是否生成 = True
        except (subprocess.CalledProcessError, FileNotFoundError):
            mp3是否生成 = False

    报告 = {
        "file": str(波形路径),
        "mp3": str(mp3路径) if mp3是否生成 else "",
        "duration_s": float(len(片段) / 采样率),
        "sample_rate": 采样率,
        "channels": 1,
        "bits": 16,
        "size_MB": round(os.path.getsize(波形路径) / 1e6, 3),
        "start_s": round(起始秒, 2),
        "end_s": round(结束秒, 2),
        "score": 最优["评分"],
        "speech_ratio": 最优["语音占比"],
        "max_pause_s": 最优["最大停顿秒"],
        "snr_db": 最优["信噪比"],
        "info_density_syl_per_s": 最优["信息密度"],
        "modulation_cv": 最优["调制系数"],
        "global_mean_snr_db": round(全局平均信噪比, 2),
        "global_cv": round(全局调制系数, 2),
        # 中文键（可选补充）
        "说明": "0.35×信息密度 + 0.25×SNR + 0.20×语音占比 + 0.20×能量调制",
    }
    (声音库目录 / "选择报告.json").write_text(
        json.dumps(报告, ensure_ascii=False, indent=2), encoding="utf-8")
    return 报告
